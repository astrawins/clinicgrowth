def ps(*paras):
    return '\n'.join(f'        <p>{p}</p>' for p in paras)


def ul(*items):
    return '        <ul class="feature-list">\n' + '\n'.join(f'          <li>{i}</li>' for i in items) + '\n        </ul>'


def steps(*items):
    return '        <div class="steps">\n' + '\n'.join(f'          <div class="step"><div><h3>{h}</h3><p>{p}</p></div></div>' for h, p in items) + '\n        </div>'


_WORK = None


def _work_items(P):
    global _WORK
    if _WORK is None:
        _WORK = re.findall(r'<a class="site[^"]*"[\s\S]*?</a>', P('work'))
    return _WORK


def works_grid(P, match=None, limit=None, h2=None, more=True):
    items = [i for i in _work_items(P) if match is None or re.search(match, re.search(r'site-spec mono">([^<]+)', i).group(1))]
    if limit:
        items = items[:limit]
    items = [i.replace('class="site big"', 'class="site"') for i in items]
    head = f'        <h2>{h2}</h2>\n' if h2 else ''
    link = '\n        <p class="more-wrap"><a class="btn btn-ghost" href="/erga/">Δείτε όλες τις δουλειές μας</a></p>' if more else ''
    return f'''    <section class="doc shell doc-work">
      <div class="wrap">
{head}        <div class="sites sites-grid">
          {"".join(items)}
        </div>{link}
      </div>
    </section>

'''


def reviews_grid(P):
    figs = re.findall(r'<figure class="review">[\s\S]*?</figure>', P('reviews'))
    seen, uniq = set(), []
    for f in figs:
        k = re.sub(r'\s+', ' ', f)
        if k not in seen:
            seen.add(k)
            uniq.append(f)
    return f'''    <section class="doc shell">
      <div class="wrap">
        <p class="rating-line"><a class="rating" href="https://www.google.com/maps?cid=13580388847976999120" target="_blank" rel="noopener"><span class="stars" aria-hidden="true">★★★★★</span> <span class="mono">5,0 · 55 κριτικές γιατρών στο Google</span></a></p>
        <div class="rev-grid">
          {"".join(uniq)}
        </div>
      </div>
    </section>

'''


